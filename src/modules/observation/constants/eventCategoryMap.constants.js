/**
 * @param {string} eventType
 * @returns {string} the EventCategory for the given EventType
 * @throws {Error} if the event type is unknown
 */
const resolveCategory = (eventType) => {
  const category = EVENT_TYPE_TO_CATEGORY[eventType];

  if (!category) {
    throw new Error(`Unknown event type: ${eventType}`);
  }

  return category;
};

