'use strict';

const { matchKeyword } = require('../keywords/keywordMatcher');
const { matchPhrase } = require('../phrases/phraseMatcher');
const { marksForSatisfaction, round2, clamp } = require('./marks');

/**
 * Scores one rubric criterion.
 *
 * Evidence is combined, not added:
 *  - Keyword coverage (K) and phrase match (P) are two views of the SAME
 *    concept, so the criterion takes the stronger of the two (max), never
 *    the sum. A student cannot earn the criterion twice.
 *  - TF-IDF / semantic similarity is corroboration only. It can lift partial
 *    direct evidence by a bounded amount, but cannot award marks on its own.
 *  - Any contradiction (negated concept, matched misconception) zeroes the
 *    criterion and sends it for review. Inconsistent evidence (mixed
 *    polarity, reversed order) caps it and sends it for review.
 */
function scoreCriterion(criterion, answer, ctx) {
  const { policy, similarity, semantic, step } = ctx;
  const conf = policy.confidence;

  const keywordResults = criterion.keywords.map((k) => matchKeyword(k, answer, null));
  // Auto-rubric phrases are whole model-answer sentences; reordering them is fine.
  const phraseResults = criterion.phrases.map((p) => matchPhrase(p, answer, null, { checkOrder: !criterion.autoGenerated }));
  const misconceptionHits = criterion.contradictions
    .map((p) => matchPhrase(p, answer, null))
    .filter((r) => !r.contradicted && r.rawScore >= policy.misconceptionThreshold);

  const K = keywordResults.length
    ? Math.min(1, keywordResults.reduce((s, r) => s + r.score, 0) / criterion.minKeywords)
    : null;
  const P = phraseResults.length ? Math.max(...phraseResults.map((r) => r.score)) : null;
  const direct = Math.max(K ?? 0, P ?? 0);
  const directSource = (P ?? -1) > (K ?? -1) ? 'phrase' : 'keywords';

  const semanticScore = typeof semantic === 'number' ? semantic : null;
  const corroborator = Math.max(similarity.score, semanticScore ?? 0);

  const flags = [];
  const contradictions = [];
  let confidence = conf.base;

  let satisfaction = direct;
  const c = policy.corroboration;
  let boost = 0;
  if (direct >= c.minDirect && direct < policy.fullCreditThreshold && corroborator >= c.minSimilarity) {
    boost = Math.min(c.maxBoost, corroborator * c.factor);
    satisfaction = Math.min(1, direct + boost);
  }

  for (const r of keywordResults) {
    if (r.contradicted) {
      contradictions.push({ type: 'negation', expected: r.keyword, found: r.matchedText });
    }
  }
  for (const r of phraseResults) {
    if (r.contradicted) {
      contradictions.push({ type: 'negation', expected: r.phrase, found: r.matchedText });
    }
  }
  for (const r of misconceptionHits) {
    contradictions.push({ type: 'misconception', expected: null, found: r.matchedText, misconception: r.phrase });
  }

  if (contradictions.length) {
    satisfaction = 0;
    confidence -= conf.contradiction;
    flags.push('contradiction');
  } else {
    if (keywordResults.some((r) => r.mixedPolarity)) {
      satisfaction = Math.min(satisfaction, policy.mixedPolarityCap);
      confidence -= conf.mixedPolarity;
      flags.push('mixed-polarity');
    }
    const fullPhrase = phraseResults.some((r) => r.score >= policy.fullCreditThreshold);
    if (!fullPhrase && phraseResults.some((r) => r.orderMismatch)) {
      satisfaction = Math.min(satisfaction, policy.orderMismatchCap);
      confidence -= conf.orderMismatch;
      flags.push('order-mismatch');
    }
  }

  if (!contradictions.length && direct < c.minDirect && corroborator >= policy.paraphraseSimilarity) {
    confidence -= conf.paraphrase;
    flags.push('possible-paraphrase');
  }
  if (direct >= 0.6 && similarity.score < policy.weakContextSimilarity && criterion.referenceTerms.length > 2) {
    confidence -= conf.weakContext;
    flags.push('weak-context');
  }
  if (keywordResults.some((r) => r.score > 0 && r.matchType.startsWith('fuzzy'))) {
    confidence -= conf.fuzzy;
    flags.push('spelling-tolerance');
  }
  if (satisfaction >= policy.minCreditThreshold && satisfaction < policy.fullCreditThreshold) {
    confidence -= conf.borderline;
    flags.push('partial');
  }
  if (criterion.autoGenerated) confidence -= conf.autoRubric;

  satisfaction = clamp(satisfaction, 0, 1);
  const awarded = marksForSatisfaction(satisfaction, criterion.marks, step, policy);

  let status;
  if (contradictions.length) status = 'contradicted';
  else if (awarded >= criterion.marks) status = 'met';
  else if (awarded > 0) status = 'partial';
  else status = 'missing';

  return {
    criterionId: criterion.id,
    description: criterion.description,
    referenceText: criterion.referenceText,
    autoGenerated: criterion.autoGenerated,
    maxMarks: criterion.marks,
    awarded,
    status,
    satisfaction: round2(satisfaction),
    confidence: round2(clamp(confidence, conf.min, 1)),
    flags,
    contradictions,
    evidence: {
      keywordCoverage: K === null ? null : round2(K),
      minKeywords: criterion.minKeywords,
      phraseScore: P === null ? null : round2(P),
      direct: round2(direct),
      directSource,
      similarity: round2(similarity.score),
      similarSegment: similarity.text,
      semanticSimilarity: semanticScore === null ? null : round2(semanticScore),
      corroborationBoost: round2(boost),
      keywords: keywordResults.map((r) => ({
        keyword: r.keyword, score: r.score, matchType: r.matchType, matchedText: r.matchedText,
      })),
      phrases: phraseResults.map((r) => ({
        phrase: r.phrase, score: round2(r.score), unordered: round2(r.unordered), matchedText: r.matchedText,
        orderMismatch: r.orderMismatch, contradicted: r.contradicted,
      })),
    },
  };
}

module.exports = { scoreCriterion };
