'use strict';

const { analyze, splitSentences } = require('../normalization/normalizer');
const { prepareTerm } = require('../keywords/termMatching');
const { matchKeyword } = require('../keywords/keywordMatcher');
const { termsFromTokens } = require('../similarity/tfidf');
const { isMultipleOf, round2, EPS } = require('./marks');
const { ALLOWED_MARK_STEPS } = require('./scoringPolicy');

class RubricError extends Error {
  constructor(message) {
    super(message);
    this.name = 'RubricError';
  }
}

const clean = (list) => (Array.isArray(list) ? list : [])
  .map((s) => (typeof s === 'string' ? s.trim() : ''))
  .filter(Boolean);

/** Throws RubricError when a question cannot be marked consistently. */
function validateQuestion(question) {
  const max = Number(question.maxMarks);
  const step = Number(question.markStep ?? 0.5);
  if (!(max > 0)) throw new RubricError('maxMarks must be greater than zero');
  if (!ALLOWED_MARK_STEPS.includes(step)) {
    throw new RubricError(`markStep must be one of ${ALLOWED_MARK_STEPS.join(', ')}`);
  }
  if (!isMultipleOf(max, step)) throw new RubricError(`maxMarks ${max} is not a multiple of markStep ${step}`);
  if (!String(question.idealAnswer || '').trim()) throw new RubricError('idealAnswer is required');

  const criteria = Array.isArray(question.criteria) ? question.criteria : [];
  if (!criteria.length) return;
  let total = 0;
  criteria.forEach((c, i) => {
    const marks = Number(c.marks);
    if (!(marks > 0)) throw new RubricError(`criterion ${i + 1}: marks must be greater than zero`);
    if (!isMultipleOf(marks, step)) throw new RubricError(`criterion ${i + 1}: marks ${marks} is not a multiple of markStep ${step}`);
    if (!String(c.description || '').trim()) throw new RubricError(`criterion ${i + 1}: description is required`);
    if (!clean(c.keywords).length && !clean(c.phrases).length) {
      throw new RubricError(`criterion ${i + 1}: provide at least one keyword or phrase`);
    }
    if (c.minKeywords != null && !(Number.isInteger(c.minKeywords) && c.minKeywords >= 1 && c.minKeywords <= clean(c.keywords).length)) {
      throw new RubricError(`criterion ${i + 1}: minKeywords must be between 1 and the number of keywords`);
    }
    total += marks;
  });
  if (Math.abs(total - max) > EPS) {
    throw new RubricError(`criterion marks add up to ${round2(total)} but the question is worth ${max}`);
  }
}

function prepareCriterion(c, synonyms, autoGenerated) {
  const keywords = clean(c.keywords).map((k) => prepareTerm(k, synonyms)).filter((t) => !t.empty);
  const phrases = clean(c.phrases).map((p) => prepareTerm(p, synonyms)).filter((t) => !t.empty);
  const contradictions = clean(c.contradictions).map((p) => prepareTerm(p, synonyms)).filter((t) => !t.empty);
  // Similarity compares against what the instructor wrote as evidence, not
  // the description ("Mentions that ..."), which is written for humans.
  const referenceText = [...clean(c.phrases), ...clean(c.keywords)].join('. ') || c.description;
  return {
    id: c.id ?? null,
    description: String(c.description).trim(),
    marks: Number(c.marks),
    keywords,
    phrases,
    contradictions,
    minKeywords: keywords.length ? Math.min(c.minKeywords || keywords.length, keywords.length) : 0,
    referenceText,
    referenceTerms: termsFromTokens(analyze(referenceText, { synonyms }).tokens),
    autoGenerated,
  };
}

/** Splits `units` mark-steps across groups by weight; every group gets one. */
function allocateUnits(weights, units) {
  const n = weights.length;
  const alloc = new Array(n).fill(1);
  let remaining = units - n;
  if (remaining <= 0) return alloc;
  const total = weights.reduce((a, b) => a + b, 0) || n;
  const exact = weights.map((w) => (w / total) * remaining);
  exact.forEach((e, i) => { alloc[i] += Math.floor(e); });
  remaining -= exact.reduce((a, e) => a + Math.floor(e), 0);
  const order = exact.map((e, i) => [e - Math.floor(e), i]).sort((a, b) => b[0] - a[0]);
  for (let k = 0; k < remaining; k += 1) alloc[order[k % n][1]] += 1;
  return alloc;
}

/**
 * Builds a rubric from the ideal answer when the instructor gave none:
 * one criterion per sentence (merged if there are more sentences than mark
 * steps), marks split by how much content each sentence carries, keywords
 * taken from the instructor's list or from the sentence's distinctive words.
 */
function autoRubric(question, synonyms) {
  const max = Number(question.maxMarks);
  const step = Number(question.markStep ?? 0.5);
  const units = Math.round(max / step);

  let sentences = splitSentences(question.idealAnswer)
    .map((text) => ({ text, analysis: analyze(text, { synonyms }) }))
    .filter((s) => s.analysis.content.length >= 2);
  if (!sentences.length) sentences = [{ text: question.idealAnswer, analysis: analyze(question.idealAnswer, { synonyms }) }];

  // Merge adjacent sentences until each group can earn at least one step.
  let groups = sentences.map((s) => [s]);
  while (groups.length > units) {
    let bestIdx = 0;
    let bestSize = Infinity;
    for (let i = 0; i + 1 < groups.length; i += 1) {
      const size = groups[i].length + groups[i + 1].length;
      if (size < bestSize) { bestSize = size; bestIdx = i; }
    }
    groups.splice(bestIdx, 2, [...groups[bestIdx], ...groups[bestIdx + 1]]);
  }

  const groupTexts = groups.map((g) => g.map((s) => s.text).join('. '));
  const groupAnalyses = groupTexts.map((t) => analyze(t, { synonyms }));

  // How many groups contain each canonical word: words unique to one group
  // are the most useful evidence for that group.
  const groupFreq = new Map();
  groupAnalyses.forEach((a) => {
    for (const canon of new Set(a.content.map((t) => t.canon))) groupFreq.set(canon, (groupFreq.get(canon) || 0) + 1);
  });

  const instructorKeywords = clean(question.keywords);
  const keywordHome = groupAnalyses.map(() => []);
  for (const kw of instructorKeywords) {
    let home = groupAnalyses.findIndex((a) => matchKeyword(kw, a, synonyms).score >= 0.8);
    if (home === -1) home = 0;
    keywordHome[home].push(kw);
  }

  const weights = groupAnalyses.map((a) => a.content.length);
  const alloc = allocateUnits(weights, units);

  const criteria = groupAnalyses.map((a, i) => {
    let keywords = keywordHome[i];
    if (!keywords.length) {
      const seen = new Set();
      keywords = a.content
        .filter((t) => t.surface.length >= 4 && !seen.has(t.canon) && seen.add(t.canon))
        .sort((x, y) => (groupFreq.get(x.canon) - groupFreq.get(y.canon)) || (y.surface.length - x.surface.length))
        .slice(0, 3)
        .map((t) => t.surface);
    }
    return prepareCriterion({
      id: `auto-${i + 1}`,
      description: `Point ${i + 1} of the model answer`,
      marks: round2(alloc[i] * step),
      keywords,
      phrases: [groupTexts[i]],
      contradictions: [],
      // Auto keywords are a guess, so two thirds of them are enough.
      minKeywords: keywordHome[i].length ? keywords.length : Math.max(1, Math.ceil(keywords.length * 0.67)),
    }, synonyms, true);
  });
  return criteria;
}

/** Validates the question and returns criteria ready for scoring. */
function buildRubric(question, synonyms) {
  validateQuestion(question);
  const given = Array.isArray(question.criteria) ? question.criteria : [];
  if (given.length) {
    return { autoGenerated: false, criteria: given.map((c) => prepareCriterion(c, synonyms, false)) };
  }
  return { autoGenerated: true, criteria: autoRubric(question, synonyms) };
}

module.exports = { buildRubric, validateQuestion, allocateUnits, RubricError };
