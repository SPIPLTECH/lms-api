'use strict';

const { analyze } = require('./normalization/normalizer');
const { SynonymDictionary } = require('./synonyms/synonymDictionary');
const { prepareTerm } = require('./keywords/termMatching');
const { matchPhrase } = require('./phrases/phraseMatcher');
const { TfidfModel, termsFromTokens, answerSegments, bestSegmentSimilarity } = require('./similarity/tfidf');
const { NullEmbeddingProvider } = require('./embeddings/embeddingProvider');
const { semanticSimilarities } = require('./embeddings/semanticSimilarity');
const { buildRubric } = require('./scoring/rubric');
const { scoreCriterion } = require('./scoring/criterionScorer');
const { mergePolicy } = require('./scoring/scoringPolicy');
const { round2, clamp } = require('./scoring/marks');
const { assertEvaluationInvariants } = require('./scoring/invariants');
const { generateFeedback } = require('./feedback/feedbackGenerator');

const ENGINE_NAME = 'rule-based';
const ENGINE_VERSION = '1.0.0';

/**
 * Question shape expected by the evaluator (independent of the database):
 * {
 *   id, prompt, idealAnswer, maxMarks, markStep (0.25 | 0.5 | 1),
 *   keywords: string[],            // used only when no criteria are given
 *   synonyms: string[][],          // question-specific synonym groups
 *   misconceptions: string[],      // statements that indicate an error
 *   criteria: [{ id, description, marks, keywords, phrases, contradictions, minKeywords }]
 * }
 */
function createRuleBasedEvaluator({ embeddingProvider = new NullEmbeddingProvider(), policy: overrides = {} } = {}) {
  const policy = mergePolicy(overrides);

  async function evaluateAnswer({ question, answerText, synonymGroups = [], dictionary = null }) {
    const base = dictionary || new SynonymDictionary(synonymGroups);
    const synonyms = base.extend(Array.isArray(question.synonyms) ? question.synonyms : []);
    const rubric = buildRubric(question, synonyms);
    const maxMarks = Number(question.maxMarks);
    const step = Number(question.markStep ?? 0.5);
    const answer = analyze(answerText, { synonyms });

    const engine = { name: ENGINE_NAME, version: ENGINE_VERSION, embeddings: embeddingProvider.name };

    if (!answer.content.length) {
      const criteria = rubric.criteria.map((c) => ({
        criterionId: c.id, description: c.description, referenceText: c.referenceText,
        autoGenerated: c.autoGenerated, maxMarks: c.marks, awarded: 0, status: 'missing',
        satisfaction: 0, confidence: 1, flags: [], contradictions: [], evidence: null,
      }));
      const result = {
        questionId: question.id ?? null, maxMarks, markStep: step, marksAwarded: 0, percentage: 0,
        confidence: 1, needsReview: false, reviewReasons: [], flags: ['empty-answer'],
        rubricAutoGenerated: rubric.autoGenerated, similarity: { overall: 0, semantic: null },
        misconceptions: [], criteria, engine,
        feedback: generateFeedback({ criteria, marksAwarded: 0, maxMarks, empty: true }),
      };
      assertEvaluationInvariants(result);
      return result;
    }

    const ideal = analyze(question.idealAnswer, { synonyms });
    const answerTerms = termsFromTokens(answer.tokens);
    const model = new TfidfModel([
      ...ideal.sentences.map((s) => termsFromTokens(s.tokens)),
      ...rubric.criteria.map((c) => c.referenceTerms),
      answerTerms,
    ]);
    const overall = model.similarity(termsFromTokens(ideal.tokens), answerTerms);
    const segments = answerSegments(answer);

    const semantic = await semanticSimilarities(
      embeddingProvider,
      rubric.criteria.map((c) => c.referenceText),
      segments.map((s) => s.text),
    );
    const semanticList = Array.isArray(semantic) ? semantic : null;

    const criteria = rubric.criteria.map((c, idx) => scoreCriterion(c, answer, {
      policy,
      step,
      similarity: bestSegmentSimilarity(model, c.referenceTerms, segments),
      semantic: semanticList ? semanticList[idx] : null,
    }));

    // Question-level misconceptions: flagged for review, not auto-deducted.
    const misconceptions = (question.misconceptions || [])
      .filter((m) => typeof m === 'string' && m.trim())
      .map((m) => matchPhrase(prepareTerm(m, synonyms), answer, null))
      .filter((r) => !r.contradicted && r.rawScore >= policy.misconceptionThreshold)
      .map((r) => ({ misconception: r.phrase, found: r.matchedText }));

    const marksAwarded = round2(clamp(criteria.reduce((s, c) => s + c.awarded, 0), 0, maxMarks));
    const ratio = marksAwarded / maxMarks;

    const flags = [];
    const reviewReasons = [];
    let confidence = Math.min(...criteria.map((c) => c.confidence));

    const matchedKeywordCount = criteria.reduce(
      (n, c) => n + c.evidence.keywords.filter((k) => k.score > 0).length, 0,
    );
    const kl = policy.keywordList;
    if (answer.sentences.length <= kl.maxSentences && answer.stopwordRatio <= kl.maxStopwordRatio
      && matchedKeywordCount >= kl.minMatchedKeywords) {
      flags.push('keyword-list');
      confidence -= policy.confidence.keywordList;
      reviewReasons.push('Answer looks like a list of keywords rather than an explanation.');
    }

    if (answer.content.length >= policy.substantiveAnswerTokens && ratio < policy.substantiveLowScoreRatio) {
      if (overall >= policy.offTopicSimilarity) {
        flags.push('low-score-substantive');
        reviewReasons.push('A substantial, on-topic answer scored low. It may be worded in a way the rules did not recognise.');
        confidence = Math.min(confidence, 0.5);
      } else {
        flags.push('off-topic');
      }
    }

    if (misconceptions.length) {
      flags.push('misconception');
      reviewReasons.push(`Possible misconception: ${misconceptions.map((m) => `"${m.found}"`).join(', ')}.`);
      confidence = Math.min(confidence, 0.4);
    }

    for (const c of criteria) {
      if (c.flags.includes('contradiction')) reviewReasons.push(`"${c.description}": the answer appears to contradict this point.`);
      else if (c.flags.includes('order-mismatch')) reviewReasons.push(`"${c.description}": the right terms appear in a different order or relationship.`);
      else if (c.flags.includes('mixed-polarity')) reviewReasons.push(`"${c.description}": the answer states this point both ways.`);
      else if (c.flags.includes('possible-paraphrase')) reviewReasons.push(`"${c.description}": no direct evidence, but the answer is similar to it. It may be a paraphrase.`);
      else if (c.confidence < policy.reviewConfidenceThreshold) reviewReasons.push(`"${c.description}": low confidence (${c.confidence}).`);
    }
    if (semantic && !Array.isArray(semantic)) flags.push('embeddings-unavailable');

    confidence = round2(clamp(confidence, policy.confidence.min, 1));
    const needsReview = reviewReasons.length > 0 || confidence < policy.reviewConfidenceThreshold;
    if (needsReview && !reviewReasons.length) reviewReasons.push(`Overall confidence ${confidence} is below the review threshold.`);

    const result = {
      questionId: question.id ?? null,
      maxMarks,
      markStep: step,
      marksAwarded,
      percentage: round2(ratio * 100),
      confidence,
      needsReview,
      reviewReasons,
      flags,
      rubricAutoGenerated: rubric.autoGenerated,
      similarity: { overall: round2(overall), semantic: semanticList ? semanticList.map(round2) : null },
      misconceptions,
      criteria,
      engine,
    };
    result.feedback = generateFeedback({ criteria, marksAwarded, maxMarks, misconceptions, flags });
    assertEvaluationInvariants(result);
    return result;
  }

  return { name: ENGINE_NAME, version: ENGINE_VERSION, policy, evaluateAnswer };
}

module.exports = { createRuleBasedEvaluator, ENGINE_NAME, ENGINE_VERSION };
